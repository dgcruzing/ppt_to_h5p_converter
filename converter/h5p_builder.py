import json
import logging
import os
import shutil
import traceback
import uuid
import zipfile
from PIL import Image


def build_h5p_package(
    image_paths: list[str],
    output_h5p_path: str,
    title: str | None = None
) -> None:
    """Constructs H5P Course Presentation JSON structures and packages image slides

    into a valid .h5p ZIP archive.

    Args:
        image_paths: List of absolute file paths to the slide PNG images.
        output_h5p_path: Target path where the .h5p file will be saved.
        title: Optional title for the presentation. Defaults to the output file's base name.
    """
    if not image_paths:
        raise ValueError("Cannot build H5P package without slide images.")

    # Ensure absolute path for output and create destination parent directory if needed
    output_h5p_path = os.path.abspath(output_h5p_path)
    os.makedirs(os.path.dirname(output_h5p_path), exist_ok=True)

    if not title:
        title = os.path.splitext(os.path.basename(output_h5p_path))[0]

    content_structure = {
        "presentation": {
            "slides": [],
            "keywordListEnabled": False,
            "globalBackgroundSelector": {},
            "keywordListAlwaysShow": False,
            "keywordListAutoHide": False,
            "keywordListOpacity": 90,
        }
    }

    try:
        with zipfile.ZipFile(output_h5p_path, "w", zipfile.ZIP_DEFLATED) as h5p_zip:
            for i, image_path in enumerate(image_paths):
                if not os.path.exists(image_path):
                    raise FileNotFoundError(f"Slide image not found: {image_path}")

                # Read dimensions using Pillow
                with Image.open(image_path) as img:
                    width, height = img.size

                # Preserve the hashed filename generated by ppt_exporter
                original_filename = os.path.basename(image_path)
                zip_slide_path = f"images/{original_filename}"

                # Write slide image into the zip archive under content/images/
                h5p_zip.write(image_path, f"content/{zip_slide_path}")

                # Construct H5P slide element structure
                h5p_slide = {
                    "elements": [
                        {
                            "x": 0,
                            "y": 0,
                            "width": 100,
                            "height": 100,
                            "action": {
                                "library": "H5P.Image 1.1",
                                "params": {
                                    "file": {
                                        "path": zip_slide_path,
                                        "mime": "image/png",
                                        "copyright": {"license": "U"},
                                        "width": width,
                                        "height": height,
                                    }
                                },
                                "subContentId": str(uuid.uuid4()),
                                "metadata": {
                                    "contentType": "Image",
                                    "license": "U",
                                    "title": f"Slide {i + 1}",
                                },
                            },
                            "alwaysDisplayComments": False,
                            "backgroundOpacity": 0,
                            "displayAsButton": False,
                            "buttonSize": "big",
                            "goToSlideType": "specified",
                            "invisible": False,
                            "solution": "",
                        }
                    ],
                    "slideBackgroundSelector": {},
                }
                content_structure["presentation"]["slides"].append(h5p_slide)

            # Write content/content.json
            h5p_zip.writestr(
                "content/content.json",
                json.dumps(content_structure, indent=2),
            )

            # Write main package metadata (h5p.json)
            h5p_metadata = {
                "title": title,
                "language": "und",
                "mainLibrary": "H5P.CoursePresentation",
                "embedTypes": ["div"],
                "license": "U",
                "defaultLanguage": "en",
                "preloadedDependencies": [
                    {
                        "machineName": "H5P.CoursePresentation",
                        "majorVersion": "1",
                        "minorVersion": "25",
                    },
                    {
                        "machineName": "FontAwesome",
                        "majorVersion": "4",
                        "minorVersion": "5",
                    },
                    {
                        "machineName": "H5P.FontIcons",
                        "majorVersion": "1",
                        "minorVersion": "0",
                    },
                    {
                        "machineName": "H5P.JoubelUI",
                        "majorVersion": "1",
                        "minorVersion": "3",
                    },
                    {
                        "machineName": "H5P.Transition",
                        "majorVersion": "1",
                        "minorVersion": "0",
                    },
                ],
            }
            h5p_zip.writestr("h5p.json", json.dumps(h5p_metadata, indent=2))

        logging.info(f"Successfully created H5P package: {output_h5p_path}")

    except Exception as e:
        logging.error(f"Error building H5P archive: {str(e)}")
        logging.debug(traceback.format_exc())
        # Cleanup partially generated file on failure
        if os.path.exists(output_h5p_path):
            try:
                os.remove(output_h5p_path)
            except Exception:
                pass
        raise RuntimeError(f"Failed to create H5P package: {str(e)}") from e


def convert_ppt_to_h5p(
    ppt_path: str, output_h5p_path: str, resolution: tuple = (1920, 1080)
) -> None:
    """High-level convenience function that exports PPT slides to temporary images

    and packages them into an H5P file, handling directory cleanup automatically.
    """
    from converter.ppt_exporter import export_slides_to_images

    temp_dir = None
    try:
        # Step 1: Export slides to temporary PNG images
        temp_dir, image_paths = export_slides_to_images(ppt_path, resolution)

        # Step 2: Build the H5P package
        build_h5p_package(image_paths, output_h5p_path)

    finally:
        # Step 3: Always purge temporary directory and files
        if temp_dir and os.path.exists(temp_dir):
            try:
                shutil.rmtree(temp_dir)
                logging.debug(f"Purged temporary directory: {temp_dir}")
            except Exception as e:
                logging.warning(
                    f"Failed to clean up temporary directory {temp_dir}: {str(e)}"
                )